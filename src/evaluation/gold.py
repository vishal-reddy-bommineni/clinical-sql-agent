"""Write reports/gold_answers.md: every question with its gold SQL and gold result.
Lets anyone check the answer key.  Usage: python -m src.evaluation.gold"""
import yaml

from src.config import QUESTIONS_PATH, REPORTS_DIR
from src.db import run_query


def main():
    qs = yaml.safe_load(QUESTIONS_PATH.read_text())["questions"]
    L = ["# Answer key (auto-generated by `python -m src.evaluation.gold`)", "",
         f"{len(qs)} questions. Each gold query was run on the MIMIC-IV demo database.", ""]
    for q in qs:
        r = run_query(q["gold_sql"])
        if not r.ok:
            raise SystemExit(f"{q['id']} failed: {r.error}")
        L += [f"## {q['id']} ({q['category']}, {q['difficulty']})", "", f"**{q['question']}**", ""]
        if q.get("trap"):
            L += [f"*Trap:* {q['trap']}", ""]
        L += ["```sql", q["gold_sql"].strip(), "```", "", r.df.to_markdown(index=False), ""]
    (REPORTS_DIR / "gold_answers.md").write_text("\n".join(L))
    print(f"Wrote {REPORTS_DIR / 'gold_answers.md'}")


if __name__ == "__main__":
    main()
