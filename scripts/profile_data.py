"""Run sql/profiling.sql and write reports/profiling.md (no API key needed).

Usage:  python -m scripts.profile_data
"""
from src.config import REPORTS_DIR, ROOT
from src.db import run_query

SQL_PATH = ROOT / "sql" / "profiling.sql"


def main():
    sql = SQL_PATH.read_text()
    out = ["# Data profiling (auto-generated by `python -m scripts.profile_data`)", "",
           "Queries: `sql/profiling.sql`. These are the checks that uncovered the traps documented in",
           "`src/catalog.yaml` and targeted by the benchmark questions.", ""]
    for chunk in sql.split("-- name:")[1:]:
        title, query = chunk.split("\n", 1)
        r = run_query(query)
        if not r.ok:
            raise SystemExit(f"{title.strip()} failed: {r.error}")
        out += [f"## {title.strip()}", "", "```sql", r.sql, "```", "", r.df.to_markdown(index=False), ""]
        print(f"\n== {title.strip()}\n{r.df.to_string(index=False)}")
    (REPORTS_DIR / "profiling.md").write_text("\n".join(out))
    print(f"\nWrote {REPORTS_DIR / 'profiling.md'}")


if __name__ == "__main__":
    main()
